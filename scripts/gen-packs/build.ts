/**
 * Build bundled packs: scripts/gen-packs/sources/<id>.txt -> content/packs/<id>.json,
 * plus content/packs/manifest.json and content/packs/index.ts (static requires for Metro).
 *
 *   npx tsx scripts/gen-packs/build.ts            # all packs that have a source file
 *   npx tsx scripts/gen-packs/build.ts movies     # one pack
 *
 * Prints a per-pack report (kept / rejected / duplicates / target) and writes it to
 * scripts/gen-packs/REPORT.md.
 */
import fs from 'node:fs';
import path from 'node:path';

import { PackSchema, type Pack, type PackMeta } from '../../content/schema';
import { SHIP_AFTER_DARK } from '../../src/config';
import { buildPhrases, parseSource } from './lib';
import { PACKS } from './packs';

const ROOT = path.resolve(__dirname, '../..');
const SRC_DIR = path.join(__dirname, 'sources');
const OUT_DIR = path.join(ROOT, 'content/packs');

function main() {
  const only = process.argv.slice(2);
  const rows: string[] = [];
  let failed = false;

  for (const brief of PACKS) {
    if (only.length && !only.includes(brief.id)) continue;
    const srcPath = path.join(SRC_DIR, `${brief.id}.txt`);
    if (!fs.existsSync(srcPath)) {
      rows.push(`| ${brief.id} | - | - | - | ${brief.target} | missing source |`);
      continue;
    }
    const adult = brief.tags.includes('adult');
    const { parsed, problems } = parseSource(fs.readFileSync(srcPath, 'utf8'));
    const { phrases, rejected, duplicates } = buildPhrases(brief.id, parsed, adult);
    const outPath = path.join(OUT_DIR, `${brief.id}.json`);
    const prev: Pack | null = fs.existsSync(outPath) ? JSON.parse(fs.readFileSync(outPath, 'utf8')) : null;
    const pack: Pack = {
      id: brief.id,
      name: brief.name,
      emoji: brief.emoji,
      description: brief.description,
      tags: brief.tags,
      version: 1,
      phrases,
    };
    // Bump version only when the phrase list actually changes.
    if (prev) pack.version = JSON.stringify(prev.phrases) === JSON.stringify(phrases) ? prev.version : prev.version + 1;

    const res = PackSchema.safeParse(pack);
    if (!res.success) {
      failed = true;
      console.error(
        `✗ ${brief.id}: schema errors\n${res.error.issues
          .slice(0, 10)
          .map((i) => `  ${i.path.join('.')}: ${i.message}`)
          .join('\n')}`,
      );
      continue;
    }
    fs.writeFileSync(outPath, JSON.stringify(pack, null, 1) + '\n');
    const status = phrases.length >= brief.target ? 'ok' : `short by ${brief.target - phrases.length}`;
    rows.push(
      `| ${brief.id} | ${phrases.length} | ${rejected.length + problems.length} | ${duplicates.length} | ${brief.target} | ${status} |`,
    );
    for (const p of [...problems, ...rejected])
      console.warn(`  ${brief.id}:${p.line} rejected "${p.text}" (${p.reason})`);
    for (const d of duplicates) console.warn(`  ${brief.id}:${d.line} duplicate "${d.text}"`);
  }

  writeIndex();
  const report = [
    '# Pack build report',
    '',
    '| pack | kept | rejected | duplicates | target | status |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(__dirname, 'REPORT.md'), report);
  console.log(report);
  if (failed) process.exit(1);
}

/** Regenerate manifest.json + index.ts from whatever pack JSON files exist. */
function writeIndex() {
  const metas: PackMeta[] = [];
  for (const brief of PACKS) {
    if (!SHIP_AFTER_DARK && brief.tags.includes('adult')) continue;
    const file = path.join(OUT_DIR, `${brief.id}.json`);
    if (!fs.existsSync(file)) continue;
    const { phrases, ...meta }: Pack = JSON.parse(fs.readFileSync(file, 'utf8'));
    metas.push({ ...meta, phraseCount: phrases.length });
  }
  fs.writeFileSync(path.join(OUT_DIR, 'manifest.json'), JSON.stringify(metas, null, 1) + '\n');
  const loaders = metas.map((m) => `  '${m.id}': () => require('./${m.id}.json') as Pack,`).join('\n');
  fs.writeFileSync(
    path.join(OUT_DIR, 'index.ts'),
    `// GENERATED by scripts/gen-packs/build.ts. Do not edit.\n` +
      `import type { Pack, PackMeta } from '../schema';\n\n` +
      `export const PACK_MANIFEST: PackMeta[] = require('./manifest.json');\n\n` +
      `/** Lazy loaders so cold start only parses packs that are actually played. */\n` +
      `export const PACK_LOADERS: Record<string, () => Pack> = {\n${loaders}\n};\n`,
  );
}

main();
